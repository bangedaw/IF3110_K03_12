// mutasi membuat skema B berbeda dari seed; semuanya harus bisa direproduksi
// oleh generator (tidak ada hal yang hanya diketahui PG tapi tak ada di model).
var mutations = []string{
	`CREATE TABLE app.reviews (
		id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		book_id BIGINT NOT NULL REFERENCES app.books (id) ON DELETE CASCADE,
		body    TEXT   NOT NULL DEFAULT ''
	)`,
	`CREATE INDEX reviews_book_idx ON app.reviews (book_id)`,
	`ALTER TABLE app.reviews ADD CONSTRAINT reviews_body_check CHECK (length(body) > 0)`,
	`ALTER TABLE app.authors DROP COLUMN homepage`,
	`ALTER TABLE app.authors ADD COLUMN bio TEXT`,
	// Kolom yang diubah tipe sengaja bukan books.title / authors.name:
	// view app.book_authors merujuk keduanya dan memblokir ALTER TYPE (0A000).
	`ALTER TABLE app.books ALTER COLUMN price TYPE numeric(12,2) USING price::numeric(12,2)`,
	`ALTER TABLE app.books ADD COLUMN isbn character varying(20)`,
	`DROP INDEX app.books_author_idx`,
	`ALTER TABLE app.attachments DROP CONSTRAINT attachments_book_id_fkey`,
}

// configOf membuat ConnConfig dari pool test (host/port db container).
func configOf(pool *pgxpool.Pool) dbms.ConnConfig {
	cc := pool.Config().ConnConfig
	return dbms.ConnConfig{
		Kind:     dbms.KindPostgres,
		Host:     cc.Host,
		Port:     int(cc.Port),
		Database: cc.Database,
		User:     cc.User,
		Password: cc.Password,
		SSLMode:  "disable",
	}
}

// snapshot mengambil model schema lewat driver postgres sungguhan.
func snapshot(t *testing.T, cfg dbms.ConnConfig) *schema.Model {
	t.Helper()
	drv, ok := dbms.DriverFor(dbms.KindPostgres)
	require.True(t, ok, "driver postgres belum terdaftar")
	conn, err := drv.Open(context.Background(), cfg)
	require.NoError(t, err)
	t.Cleanup(func() { _ = conn.Close() })

	model, err := conn.Inspector().Snapshot(context.Background())
	require.NoError(t, err)
	return model
}

// TestGeneratedSQL_MenyamakanSkemaAKeB: SQL hasil generator diterapkan ke
// database A membuat skema A identik dengan skema B (diff-nya kosong).
func TestGeneratedSQL_MenyamakanSkemaAKeB(t *testing.T) {
	ctx := context.Background()

	poolA := testutil.NewPostgresTarget(t)
	t.Cleanup(poolA.Close)
	poolB := testutil.NewPostgresTarget(t)
	t.Cleanup(poolB.Close)

	for _, m := range mutations {
		_, err := poolB.Exec(ctx, m)
		require.NoErrorf(t, err, "mutasi skema B: %s", m)
	}

	modelA := snapshot(t, configOf(poolA))
	modelB := snapshot(t, configOf(poolB))

	changes := schemadiff.Diff(modelA, modelB)
	require.NotEmpty(t, changes, "seed A dan B harus berbeda setelah mutasi")

	res, err := schemadiff.Generate(schema.KindPostgres, changes)
	require.NoError(t, err)
	require.NotEmpty(t, res.Statements)

	for i, stmt := range res.Statements {
		_, err := poolA.Exec(ctx, stmt)
		require.NoErrorf(t, err, "pernyataan #%d gagal:\n%s", i, stmt)
	}

	after := snapshot(t, configOf(poolA))
	rest := schemadiff.Diff(after, modelB)
	require.Empty(t, rest, "skema A setelah apply SQL harus sama dengan B; sisa diff: %+v", rest)
}
